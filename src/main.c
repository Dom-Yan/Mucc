//---------- Embedded files --------------------------------------------------

// The single mucc binary (`make build/mucc`) carries its headers and the
// C library inside it: build/files.s, generated by the Makefile, defines
// this table with each file's bytes (by .incbin), ending with an entry
// whose path is NULL. Their paths start with EMBED_DIR, as in
// "<mucc>/musl/include/stdio.h", which is no real file, and they are read
// from memory. A mucc built without that file has this empty table.
typedef struct {
  char *path;
  char *data;
  size_t size;
} EmbeddedFile;

__attribute__((weak)) EmbeddedFile mucc_files[1];

#define EMBED_DIR "<mucc>"

static EmbeddedFile *find_embedded(char *path) {
  static HashMap map;
  if (strncmp(path, EMBED_DIR "/", strlen(EMBED_DIR) + 1))
    return NULL;
  if (!map.capacity)
    for (EmbeddedFile *f = mucc_files; f->path; f++)
      hashmap_put(&map, f->path, f);
  return hashmap_get(&map, path);
}

// Opens `path` for reading, from memory if it's embedded.
FILE *open_input_file(char *path) {
  EmbeddedFile *f = find_embedded(path);
  if (f)
    return fmemopen(f->data, f->size, "rb");
  return fopen(path, "rb");
}

//---------- Include paths and the C library (--libc) ------------------------

// Returns the directory containing the running mucc binary. argv[0] is
// only a bare "mucc" when mucc is found via $PATH, so ask the kernel.
static char *exe_dir(char *argv0) {
  char buf[4096];
  ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
  if (n == -1)
    return dirname(strdup(argv0));
  buf[n] = '\0';
  return dirname(strdup(buf));
}

// Are `a` and `b` the same directory, under any spelling?
static bool same_dir(char *a, char *b) {
  struct stat st, st2;
  return !stat(a, &st) && !stat(b, &st2) && st.st_dev == st2.st_dev &&
         st.st_ino == st2.st_ino;
}

static bool in_include_paths(char *dir) {
  for (int i = 0; i < include_paths.len; i++)
    if (same_dir(include_paths.data[i], dir))
      return true;
  return false;
}

// A C library mucc compiles and links against: where its headers,
// startup files and libraries are, and what else to link. This is the
// only place with system paths. --libc=system is glibc as installed,
// with gcc's startup files and runtime library. --libc=mucc is the musl
// `make libc` builds, always linked statically, with nothing from gcc.
typedef struct {
  char *name;          // as in --libc=
  char **include_dirs; // its headers, searched after mucc's own
  char **crt_dirs;     // the first with crti.o has crt1.o, crti.o, crtn.o
  char **gcc_dirs;     // the first match has crtbegin.o, crtend.o, libgcc
  char **lib_dirs;     // searched for -l, after -L and the gcc directory
  char **static_libs;  // linked after the inputs with -static
  char **shared_libs;  // otherwise (in ld's syntax)
  char *dynamic_linker;
} Libc;

static char *system_include_dirs[] = {
  "/usr/local/include", "/usr/include/x86_64-linux-gnu", "/usr/include", NULL,
};
static char *system_crt_dirs[] = {
  "/usr/lib/x86_64-linux-gnu", "/usr/lib64", NULL,
};
static char *system_gcc_dirs[] = {
  "/usr/lib/gcc/x86_64-linux-gnu/*",
  "/usr/lib/gcc/x86_64-pc-linux-gnu/*", // Gentoo
  "/usr/lib/gcc/x86_64-redhat-linux/*", // Fedora
  NULL,
};
static char *system_lib_dirs[] = {
  "/usr/lib/x86_64-linux-gnu", "/usr/lib64", "/lib64",
  "/usr/lib/x86_64-pc-linux-gnu", "/usr/lib/x86_64-redhat-linux", "/usr/lib",
  "/lib", NULL,
};
static char *system_static_libs[] = {"-lgcc", "-lgcc_eh", "-lc", NULL};
static char *system_shared_libs[] = {
  "-lc", "-lgcc", "--as-needed", "-lgcc_s", "--no-as-needed", NULL,
};

// Filled in by find_musl(), next to the mucc binary.
static char *musl_include_dirs[2];
static char *musl_lib_dirs[2];
static char *no_dirs[] = {NULL};
static char *musl_static_libs[] = {"-lc", NULL};

static Libc libcs[] = {
  {"system", system_include_dirs, system_crt_dirs, system_gcc_dirs,
   system_lib_dirs, system_static_libs, system_shared_libs,
   "/lib64/ld-linux-x86-64.so.2"},
  {"mucc", musl_include_dirs, musl_lib_dirs, no_dirs, musl_lib_dirs,
   musl_static_libs, NULL, NULL},
};

// --libc=, or by default the one inside the binary (the single binary,
// build/mucc, has musl), else the system's. See main().
static Libc *libc;

static void set_libc(char *name) {
  for (int i = 0; i < sizeof(libcs) / sizeof(*libcs); i++) {
    if (!strcmp(libcs[i].name, name)) {
      libc = &libcs[i];
      return;
    }
  }
  error("unknown C library: --libc=%s", name);
}

// musl, as `make libc` builds it: inside the binary, in build/musl next
// to it when run from the source tree, or in ../lib/mucc/musl after
// `make install`, with its headers in include/ and crt1.o, crti.o,
// crtn.o and libc.a in lib/.
static void find_musl(char *argv0) {
  if (find_embedded(EMBED_DIR "/musl/lib/libc.a")) {
    musl_include_dirs[0] = EMBED_DIR "/musl/include";
    musl_lib_dirs[0] = EMBED_DIR "/musl/lib";
    return;
  }

  char *dir = format("%s/build/musl", exe_dir(argv0));
  if (!file_exists(format("%s/lib/libc.a", dir)))
    dir = format("%s/../lib/mucc/musl", exe_dir(argv0));
  if (!file_exists(format("%s/lib/libc.a", dir)))
    error("--libc=mucc: the C library isn't built; run `make libc`");

  // Its real path, the same through a symlink (as the Makefile's
  // stage2-musl/build is), since header paths go into the debug info.
  dir = realpath(dir, NULL);
  musl_include_dirs[0] = format("%s/include", dir);
  musl_lib_dirs[0] = format("%s/lib", dir);
}

static void add_default_include_paths(char *argv0) {
  // mucc's own headers are inside the binary, in ./include next to it
  // when run from the source tree, or in ../lib/mucc/include after
  // `make install`.
  char *dir = exe_dir(argv0);
  char *inc = format("%s/include", dir);
  if (find_embedded(EMBED_DIR "/include/stddef.h"))
    inc = EMBED_DIR "/include";
  else if (!file_exists(inc))
    inc = format("%s/../lib/mucc/include", dir);

  // mucc's headers and the C library's are the system headers: -MMD
  // leaves them out, and warnings and some type checks don't apply to
  // them. -I directories, added to include_paths before this runs, are
  // not.
  char **sys = libc->include_dirs;
  int nsys = 0;
  while (sys[nsys])
    nsys++;

  // As with gcc, -I of a system directory is ignored, and it's searched
  // in its place, after mucc's headers. (CPython's build passes
  // -I/usr/include/x86_64-linux-gnu, which put glibc's <sys/cdefs.h>
  // before mucc's, and glibc's then dropped every __attribute__.)
  StringArray user = include_paths;
  include_paths = (StringArray){};
  for (int i = 0; i < user.len; i++) {
    bool is_sys = false;
    for (int j = 0; j < nsys; j++)
      is_sys |= same_dir(user.data[i], sys[j]);
    if (!is_sys)
      strarray_push(&include_paths, user.data[i]);
  }

  // mucc's own headers, given with -I too (as the Makefile's -Iinclude
  // does), are searched once, where -I put them: listed twice,
  // include/sys/cdefs.h, which does #include_next of its own name, would
  // be read twice.
  if (!in_include_paths(inc))
    strarray_push(&include_paths, inc);
  strarray_push(&std_include_paths, inc);

  for (int i = 0; i < nsys; i++) {
    strarray_push(&include_paths, sys[i]);
    strarray_push(&std_include_paths, sys[i]);
  }
}

//---------- Argument parsing ------------------------------------------------

static void usage(int status) {
  fprintf(stderr, "mucc [ -o <path> ] <file>\n");
  exit(status);
}

static bool take_arg(char *arg) {
  char *x[] = {
    "-o", "-I", "-L", "-D", "-U", "-idirafter", "-isystem", "-include", "-x",
    "-MF", "-MT", "-Xlinker",
  };

  for (int i = 0; i < sizeof(x) / sizeof(*x); i++)
    if (!strcmp(arg, x[i]))
      return true;
  return false;
}

static void define(char *str) {
  char *eq = strchr(str, '=');
  if (eq)
    define_macro(strndup(str, eq - str), eq + 1);
  else
    define_macro(str, "1");
}

// Adds an input file (or -l, -Wl,), with the -x given before it.
static void add_input(char *path) {
  strarray_push(&input_paths, path);
  input_types = realloc(input_types, sizeof(FileType) * input_paths.len);
  input_types[input_paths.len - 1] = opt_x;
}

static FileType parse_opt_x(char *s) {
  if (!strcmp(s, "c"))
    return FILE_C;
  if (!strcmp(s, "assembler"))
    return FILE_ASM;
  if (!strcmp(s, "assembler-with-cpp"))
    return FILE_ASM_CPP;
  if (!strcmp(s, "none"))
    return FILE_NONE;
  error("<command line>: unknown argument for -x: %s", s);
}

static char *quote_makefile(char *s) {
  char *buf = calloc(1, strlen(s) * 2 + 1);

  for (int i = 0, j = 0; s[i]; i++) {
    switch (s[i]) {
    case '$':
      buf[j++] = '$';
      buf[j++] = '$';
      break;
    case '#':
      buf[j++] = '\\';
      buf[j++] = '#';
      break;
    case ' ':
    case '\t':
      for (int k = i - 1; k >= 0 && s[k] == '\\'; k--)
        buf[j++] = '\\';
      buf[j++] = '\\';
      buf[j++] = s[i];
      break;
    default:
      buf[j++] = s[i];
      break;
    }
  }
  return buf;
}

static bool is_std_option(char *arg) {
  return !strncmp(arg, "-std=", 5) || !strcmp(arg, "-ansi");
}

// -std=c17 or gnu17 and so on (the GNU and ISO modes are the same) sets
// opt_std. It's read before the other options, since predefined macros
// like __STDC_VERSION__ depend on it and -D and -U come after them.
static void set_std(int argc, char **argv) {
  static char *names[] = {"c89", "c90", "c99", "c9x", "c11", "c1x",
                          "c17", "c18", "c2x", "c23"};
  static int years[] = {1989, 1989, 1999, 1999, 2011, 2011, 2017, 2017, 2023, 2023};

  for (int i = 1; i < argc; i++) {
    if (!is_std_option(argv[i]))
      continue;
    char *s = argv[i][1] == 'a' ? "c89" : argv[i] + 5;
    if (!strncmp(s, "gnu", 3))
      s = format("c%s", s + 3);
    int k = 0;
    while (k < 10 && strcmp(s, names[k]))
      k++;
    if (k == 10)
      error("unsupported standard: %s", argv[i]);
    opt_std = years[k];
  }
}

